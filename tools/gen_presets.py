#!/usr/bin/env python3
"""Generate src/editor/Presets.h from tools/presets.json (dumped from the approved mockup)."""
import json
d = json.load(open('tools/presets.json'))
def F(v):
    t = '%.9g' % v
    return t + ('f' if ('.' in t or 'e' in t) else '.0f')
o = ['// Generated by tools/gen_presets.py from the mockup. Do not edit by hand.', '#pragma once', 'namespace presets {',
     'struct KV { const char* id; float v; };',
     'struct Pre { const char* name; const char* type; int page; const KV* kv; int n; };',
     'struct Band { const char* name; const KV* kv; int n; };']
pre = []
for pg, bank in enumerate(d['FACT']):
    for i, p in enumerate(bank):
        nm = 'p%d_%d' % (pg, i)
        o.append('inline constexpr KV %s[] = { %s };' % (nm, ', '.join('{ "%s", %s }' % (k, F(float(v))) for k, v in p['p'].items())))
        pre.append('  { "%s", "%s", %d, %s, %d },' % (p['name'].replace('"', "'"), p['type'], pg, nm, len(p['p'])))
o.append('inline constexpr Pre kPre[] = {'); o += pre; o.append('};')
o.append('inline constexpr int kNumPre = %d;' % len(pre))
bp = []
for i, b in enumerate(d['BANDP']):
    o.append('inline constexpr KV band%d[] = { %s };' % (i, ', '.join('{ "%s", %s }' % (k, F(float(v))) for k, v in b['p'].items())))
    bp.append('  { "%s", band%d, %d },' % (b['n'], i, len(b['p'])))
o.append('inline constexpr Band kBand[] = {'); o += bp; o.append('};')
o.append('inline constexpr int kNumBand = %d;' % len(bp))
o.append('} // namespace presets')
open('src/editor/Presets.h', 'w').write('\n'.join(o) + '\n')
print('presets', len(pre), 'band', len(bp))
