#!/usr/bin/env python3
"""Generates src/editor/Layout.h from tools/layout.json (dumped from the approved mockup by tools/dump_layout.py)."""
import json
d=json.load(open('tools/layout.json'))
def q(s): return '"'+s.replace('\\','\\\\').replace('"','\\"').replace('\n',' ')+'"'
def F(v):
    t='%g'%v
    return t+('f' if ('.' in t or 'e' in t) else '.0f')
def rc(r): return '{ '+', '.join(F(v) for v in r)+' }'
def argb(c): return '0x%02x%02x%02x%02x'%(round(c[3]*255),int(c[0]),int(c[1]),int(c[2]))
BX=[60,352,643,935]
def bandOf(r):
    if r[1]<300 or r[1]>660: return -1
    cx=r[0]+r[2]/2
    for i,x in enumerate(BX):
        if x<=cx<x+290: return i
    return -1
kinds={'knob':0,'toggle':1,'power':2,'radio':3,'seg':4,'select':5}
o=['// GENERATED by tools/gen_layout.py from tools/layout.json. Do not edit by hand.','#pragma once','namespace layout {',
'struct Rc { float x, y, w, h; };',
'struct Box { Rc r; unsigned bg; float bd; unsigned bc; float rad; const char* cls; };',
'struct Txt { const char* s; Rc r; float fs; int fw; bool mono, italic; float ls; unsigned col; bool upper; const char* cls; };',
'struct Ctl { int kind; const char* pid; int idx; Rc r; const char* tip; const char* label; Rc labR, valR, knobR; unsigned color; const char* text; const char* cls; const char* opts; int off; };',
'struct Cv { int id; Rc r; const char* tip; const char* cls; int band; };',
'struct Oth { const char* tag; const char* id; const char* text; Rc r; const char* tip; const char* cls; int band; };',
'constexpr int W = 1280, H = 720, RIG = 40;   // the preview rig strip (40 px) is not part of the plugin',
'constexpr int NB = 4;',
'inline constexpr Rc cheekL { 0, 0, 52, 720 }, cheekR { 1228, 0, 52, 720 };']
for pg in d:
    n=pg['page']
    o.append('// ---- page %d'%n)
    o.append('inline constexpr Box boxes%d[] = {'%n)
    for b in pg['box']:
        o.append('  { %s, %s, %s, %s, %s, %s },'%(rc(b['r']),argb(b['bg']),F(b['bd']),argb(b['bc']),F(b['rad']),q(b['c'])))
    o.append('};')
    o.append('inline constexpr Txt txts%d[] = {'%n)
    for t in pg['txt']:
        if t['c'] in ('rd','B','tag','SPAN','LABEL','nm','mixnote') or t['t'].startswith(('Latency','Limiter GR')): continue
        if t['r'][1]>652: continue
        o.append('  { %s, %s, %s, %d, %s, %s, %s, %s, %s, %s },'%(q(t['t']),rc(t['r']),F(t['fs']),t['fw'],str(t['mono']).lower(),str(t['it']).lower(),F(t['ls']),argb(t['col']),str(t['tt']=='uppercase').lower(),q(t['c'])))
    o.append('};')
    o.append('inline constexpr Ctl ctls%d[] = {'%n)
    for c in pg['ctl']:
        z='{ 0, 0, 0, 0 }'
        o.append('  { %d, %s, %d, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %d },'%(kinds[c['kind']],q(c['pid']),c['idx'],rc(c['r']),q(c['tip']),q(c.get('label','')),rc(c['labR']) if c.get('labR') else z,rc(c['valR']) if c.get('valR') else z,rc(c['knobR']) if c.get('knobR') else z,'0x'+('ff'+c['color'][1:7] if c.get('color','').startswith('#') and len(c['color'])>=7 else 'ff%02x%02x%02x'%tuple(int(x) for x in __import__('re').findall(r'\d+',c['color'])[:3]) if c.get('color','').startswith('rgb') else 'ff02EBBA'),q(c['text']),q(c['cls']),q(json.dumps(c['opts'])) if c.get('opts') else '""',c.get('off',0)))
    o.append('};')
    o.append('inline constexpr Cv cvs%d[] = {'%n)
    for i,c in enumerate(pg['cv']):
        if c['r'][0] in (0,1228) and c['r'][2]==52: continue
        o.append('  { %d, %s, %s, %s, %d },'%(i,rc(c['r']),q(c['tip']),q(c['cls']),bandOf(c['r'])))
    o.append('};')
    o.append('inline constexpr Oth oths%d[] = {'%n)
    for t in pg['other']:
        if t['tag'] not in ('BUTTON','SELECT','DIV','SPAN') : continue
        if t['r'][1]>652 or t['r'][0]<52 or t['r'][0]>1228: continue
        if t['tag'] in ('DIV','SPAN') and not t['cls'] in ('nm','mixnote','cap') and not t['text'].startswith(('Latency','Limiter')): continue
        o.append('  { %s, %s, %s, %s, %s, %s, %d },'%(q(t['tag']),q(t['id']),q(t['text']),rc(t['r']),q(t['tip']),q(t['cls']),bandOf(t['r'])))
    o.append('};')
o.append('}')
open('src/editor/Layout.h','w').write('\n'.join(o)+'\n')
print('ok',len('\n'.join(o)))
