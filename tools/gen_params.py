#!/usr/bin/env python3
"""Generates src/plugin/ParamTable.h from tools/params.json (dumped from the approved mockup)."""
import json
d=json.load(open('tools/params.json'))
skip=('.view','.zoom','.sel','.patI','.span','.fft','.vu','.link','.dGrid')
rows=[]
for p in d:
    if p['id'].endswith(skip) or p['id'] in ('m.fft','m.vu','s.link'): continue
    rows.append(p)
extra=[
 dict(id='m.linear',min=0,max=1,def_=1,int=1,name='Linear Phase Crossovers'),
 dict(id='m.la',min=1,max=7.5,def_=7.5,int=0,name='Limiter Lookahead'),
 dict(id='m.rms',min=0,max=1,def_=0,int=1,name='RMS Detector'),
 dict(id='m.auto',min=0,max=1,def_=1,int=1,name='Autogain'),
 dict(id='m.steps',min=0,max=1,def_=0,int=1,name='Integer Ratios'),
 dict(id='s.feed',min=0,max=1,def_=0,int=1,name='Sidechain Feed'),
 dict(id='m.bypass',min=0,max=1,def_=0,int=1,name='Bypass'),
]
names={'m':'Main','s':'Sidechain'}
def F(v):
    t='%g'%v
    return (t if ('.' in t or 'e' in t) else t+'.0')+'f'
def nice(i):
    a,b=i.split('.',1)
    pre='Main ' if a=='m' else ('SC ' if a=='s' else 'Band %d '%(int(a[1])+1))
    return pre+b
out=['// Generated by tools/gen_params.py from the mockup parameter table. Do not edit by hand.','#pragma once','namespace mp {','struct PDef { const char* id; const char* name; float mn, mx, df; bool log, isInt; };','inline constexpr PDef kParams[] = {']
for p in rows:
    out.append('    {"%s","%s",%s,%s,%s,%s,%s},'%(p['id'],nice(p['id']),F(p['min']),F(p['max']),F(p['def']),'true' if p.get('log') else 'false','true' if p.get('int') else 'false'))
for p in extra:
    out.append('    {"%s","%s",%s,%s,%s,false,%s},'%(p['id'],p['name'],F(p['min']),F(p['max']),F(p['def_']),'true' if p['int'] else 'false'))
out+=['};','inline constexpr int kNumParams = (int)(sizeof(kParams)/sizeof(kParams[0]));','}']
open('src/plugin/ParamTable.h','w').write('\n'.join(out)+'\n')
print(len(rows)+len(extra),'params')

# ---- ParamMap.h: copies the host parameter values (kParams order) into the core structs
allp=[p['id'] for p in rows]+[p['id'] for p in extra]
ix={i:n for n,i in enumerate(allp)}
mm={'on':'on','bands':'bands','slope':'slope','mix':'mix','inG':'inG','inPan':'inPan','outG':'outG','postG':'postG','outPan':'outPan','limOn':'limOn','ceil':'ceil','linear':'linearPhase','la':'sysLA','rms':'rms','auto':'autoGain','steps':'ratioSteps'}
lines=['// Generated by tools/gen_params.py. Do not edit by hand.','#pragma once','#include "../core/MultiPawCore.h"','#include "ParamTable.h"','namespace mp {','inline void applyParams(const float* v, multipaw::MbcP& m, multipaw::ScP& s, bool& bypass) {','    bypass = v[%d] > 0.5f;'%ix['m.bypass']]
used={'m.bypass'}
def put(lhs,i,kind):
    used.add(i)
    e='v[%d]'%ix[i]
    if kind=='b': e+=' > 0.5f'
    elif kind=='i': e='(int) (%s + 0.5f)'%e
    lines.append('    %s = %s;'%(lhs,e))
isb=lambda i:[p for p in rows+extra if p['id']==i][0]
for k,f in mm.items():
    i='m.'+k
    p=isb(i); kind='b' if f in('on','limOn','linearPhase','rms','autoGain','ratioSteps') else ('i' if f in('bands','slope') else 'f')
    put('m.'+f,i,kind)
for n,k in enumerate(['x1','x2','x3']): put('m.x[%d]'%n,'m.'+k,'f')
bm={'on':'on','cOn':'cOn','knee':'knee','lOn':'lOn','mute':'mute','solo':'solo','dOn':'dOn','dX2':'dX2','dFlip':'dFlip','dPre':'dPre','thr':'thr','rat':'u','atk':'atk','rel':'rel','boost':'boost','lRel':'lRel','lOut':'lOut','inG':'inG','outG':'outG','mix':'mix','dStr':'dStr'}
bools={'on','cOn','knee','lOn','mute','solo','dOn','dX2','dFlip','dPre'}
for b in range(4):
    for k,f in bm.items(): put('m.b[%d].%s'%(b,f),'b%d.%s'%(b,k),'b' if k in bools else 'f')
sm={'on':'on','trig':'trig','sens':'sens','ftype':'ftype','inG':'inG','outG':'outG','split':'split','listen':'listen','lowVol':'lowVol','hiVol':'hiVol','grid':'grid','offset':'offset','feed':'feed','e1f':'e1f','e1g':'e1g','e1w':'e1w','e2f':'e2f','e2g':'e2g','e2w':'e2w'}
for k in ['lStr','lAtk','lAtkC','lHold','lRel','lRelC','hStr','hAtk','hAtkC','hHold','hRel','hRelC']: sm[k]=k
for k,f in sm.items():
    put('s.'+f,'s.'+k,'b' if k=='on' else ('i' if k in('trig','ftype','listen','grid','feed') else 'f'))
lines+=['}','}']
missing=[i for i in allp if i not in used]
assert not missing, missing
open('src/plugin/ParamMap.h','w').write('\n'.join(lines)+'\n'); print('mapped',len(used))
